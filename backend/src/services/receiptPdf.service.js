import PDFDocument from "pdfkit";
import { formatNaira } from "../utils/money.js";

export const generateReceiptPDF = ({ school, payment }) => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ size: "A5", margin: 30 });
      const chunks = [];
      doc.on("data", (c) => chunks.push(c));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", reject);

      const { studentId: student, billId: bill, recordedBy } = payment;

      // Header
      doc.fontSize(16).font("Helvetica-Bold").text(school.name.toUpperCase(), { align: "center" });
      if (school.address) doc.fontSize(9).font("Helvetica").text(school.address, { align: "center" });
      if (school.phone) doc.fontSize(9).text(`Tel: ${school.phone}`, { align: "center" });
      doc.moveDown(0.5);
      doc.fontSize(13).font("Helvetica-Bold").fillColor("#0b2b4f")
        .text("OFFICIAL RECEIPT", { align: "center" });
      doc.fillColor("black").moveDown(0.7);

      // Receipt meta
      doc.fontSize(10).font("Helvetica-Bold");
      doc.text(`Receipt No: `, { continued: true }).font("Helvetica").text(payment.receiptNumber);
      doc.font("Helvetica-Bold").text(`Date: `, { continued: true }).font("Helvetica")
        .text(new Date(payment.paidAt).toLocaleString("en-NG"));

      doc.moveDown(0.5);
      doc.moveTo(30, doc.y).lineTo(560, doc.y).stroke();
      doc.moveDown(0.5);

      // Pupil info
      doc.fontSize(10).font("Helvetica-Bold").text("Pupil");
      doc.font("Helvetica");
      doc.text(`Name: ${student.fullName}`);
      doc.text(`Admission No: ${student.admissionNumber}`);
      doc.text(`Class: ${student.className}`);
      if (student.guardian?.fullName) {
        doc.text(`Guardian: ${student.guardian.fullName} (${student.guardian.phone})`);
      }

      doc.moveDown(0.5);
      doc.font("Helvetica-Bold").text("Payment For");
      doc.font("Helvetica");
      doc.text(`${bill.session} · ${bill.term}`);
      if (bill.items?.length) {
        bill.items.forEach((item) => {
          doc.text(`  • ${item.name} — ${formatNaira(item.amountKobo)}`);
        });
      }

      doc.moveDown(0.5);
      doc.moveTo(30, doc.y).lineTo(560, doc.y).stroke();
      doc.moveDown(0.5);

      // Amounts
      doc.fontSize(11).font("Helvetica-Bold");
      doc.text("Amount Paid:", { continued: true }).font("Helvetica-Bold").fillColor("#166534")
        .text(` ${formatNaira(payment.amountKobo)}`);
      doc.fillColor("black");

      doc.fontSize(10).font("Helvetica")
        .text(`Method: ${payment.method.replace("_", " ")}`);
      if (payment.reference) doc.text(`Reference: ${payment.reference}`);
      if (payment.bankName) doc.text(`Bank: ${payment.bankName}`);
      if (payment.payerName) doc.text(`Payer: ${payment.payerName}`);

      doc.moveDown(0.7);
      doc.font("Helvetica-Bold").text("Bill Summary");
      doc.font("Helvetica");
      doc.text(`Total Billed: ${formatNaira(bill.totalKobo)}`);
      doc.text(`Total Paid:   ${formatNaira(bill.paidKobo)}`);
      doc.text(`Balance:      ${formatNaira(bill.balanceKobo)}`);

      doc.moveDown(1);
      doc.fontSize(8).font("Helvetica").fillColor("gray");
      doc.text(`Recorded by: ${recordedBy?.fullName || "—"}`);
      doc.text(`Generated by CodeSmartNG Academic on ${new Date().toLocaleDateString()}`);
      doc.fillColor("black");

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
};
