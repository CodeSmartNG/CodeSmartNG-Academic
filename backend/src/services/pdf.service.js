import PDFDocument from "pdfkit";

export const generateReportCardPDF = (data) => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ size: "A4", margin: 50 });
      const chunks = [];
      doc.on("data", (c) => chunks.push(c));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", reject);

      const { school, student, class: cls, session, term, results, summary } = data;

      // ── Header ─────────────────────────────────────────────
      doc.fontSize(20).font("Helvetica-Bold").fillColor("#0b2b4f")
        .text(school.name.toUpperCase(), { align: "center" });
      
      doc.fontSize(10).font("Helvetica").fillColor("#64748b")
        .text(school.address || "", { align: "center" });
      
      doc.moveDown(0.5);
      
      doc.fontSize(12).font("Helvetica-Bold").fillColor("#ffb347")
        .text(`${term} Report Card · ${session}`, { align: "center" });

      doc.moveDown(1);

      // ── Pupil Info ─────────────────────────────────────────
      doc.fontSize(10).fillColor("#000");
      doc.font("Helvetica-Bold").text("Pupil Name: ", { continued: true })
        .font("Helvetica").text(student.fullName);
      
      doc.font("Helvetica-Bold").text("Admission No: ", { continued: true })
        .font("Helvetica").text(student.admissionNumber);
      
      doc.font("Helvetica-Bold").text("Class: ", { continued: true })
        .font("Helvetica").text(cls?.name || student.className);
      
      doc.font("Helvetica-Bold").text("Gender: ", { continued: true })
        .font("Helvetica").text(student.gender);

      doc.moveDown(1);

      // ── Results Table ──────────────────────────────────────
      doc.font("Helvetica-Bold").fontSize(10).fillColor("#0b2b4f");
      doc.text("SUBJECT", 50, doc.y);
      doc.text("SCORE", 250, doc.y - 12);
      doc.text("GRADE", 350, doc.y - 12);
      doc.text("REMARK", 420, doc.y - 12);

      doc.moveTo(50, doc.y + 3).lineTo(550, doc.y + 3).stroke("#cbd5e1");
      doc.moveDown(0.5);

      doc.font("Helvetica").fontSize(10).fillColor("#334155");
      
      results.forEach((r) => {
        doc.text(r.subjectId?.name || "—", 50, doc.y, { width: 190 });
        doc.text(`${r.totalScore ?? 0}/${r.maxPossible ?? 100}`, 250, doc.y - 12, { width: 90 });
        doc.text(r.grade || "—", 350, doc.y - 12, { width: 60 });
        doc.text(r.remark || "—", 420, doc.y - 12, { width: 130 });
        doc.moveDown(0.5);
      });

      doc.moveTo(50, doc.y + 3).lineTo(550, doc.y + 3).stroke("#cbd5e1");
      doc.moveDown(1);

      // ── Summary ────────────────────────────────────────────
      doc.font("Helvetica-Bold").fontSize(10).fillColor("#0b2b4f");
      doc.text(`Total Score: ${summary?.overallTotal ?? 0}`);
      doc.text(`Average: ${summary?.overallAverage != null ? summary.overallAverage.toFixed(1) + "%" : "—"}`);
      doc.text(`Overall Grade: ${summary?.overallGrade ?? "—"}`);
      doc.text(`Position: ${summary?.positionInClass ?? "—"} of ${summary?.totalPupilsInClass ?? "—"}`);

      doc.moveDown(1.5);

      // ── Comments ───────────────────────────────────────────
      doc.font("Helvetica-Bold").fontSize(10).fillColor("#0b2b4f").text("Form Teacher's Comment:");
      doc.font("Helvetica").fillColor("#334155").text(summary?.formTeacherComment || "Keep up the good work!");
      
      doc.moveDown(0.8);
      
      doc.font("Helvetica-Bold").fillColor("#0b2b4f").text("Head Teacher's Comment:");
      doc.font("Helvetica").fillColor("#334155").text(summary?.headTeacherComment || "Keep up the good work!");

      doc.moveDown(2);

      // ── Footer ─────────────────────────────────────────────
      doc.fontSize(8).font("Helvetica").fillColor("#94a3b8")
        .text(`Generated by CodeSmartNG Academic · ${new Date().toLocaleDateString()}`, { align: "center" });

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
};
